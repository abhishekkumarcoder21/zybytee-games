// Helper functions
export function getGameBySlug(slug: string): Game | undefined {
  return games.find((g) => g.slug === slug);
}

export function getGamesByCategory(category: string): Game[] {
  return games.filter((g) => g.category === category);
}

export function getFeaturedGames(): Game[] {
  return games.filter((g) => g.featured);
}

export function getTrendingGames(): Game[] {
  return games.filter((g) => g.trending);
}

export function getNewGames(): Game[] {
  return games.filter((g) => g.isNew);
}

export function searchGames(query: string): Game[] {
  const q = query.toLowerCase();
  return games.filter(
    (g) =>
      g.title.toLowerCase().includes(q) ||
      g.description.toLowerCase().includes(q) ||
      g.tags.some((t) => t.toLowerCase().includes(q)) ||
      g.category.toLowerCase().includes(q)
  );
}

export function getPopularGames(limit = 10): Game[] {
  return [...games].sort((a, b) => b.playCount - a.playCount).slice(0, limit);
}

export function getTopRatedGames(limit = 10): Game[] {
  return [...games].sort((a, b) => b.rating - a.rating).slice(0, limit);
}
